def is_prime(n):
    """
    Check if n is a prime number.
    Uses trial division with O(sqrt(n)) complexity.
    """
    if n < 2:
        return False
    if n == 2:
        return True
    if n % 2 == 0:
        return False

    i = 3
    while i * i <= n:
        if n % i == 0:
            return False
        i += 2
    return True
